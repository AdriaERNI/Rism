#!/usr/bin/env python3
"""Generate llms.txt + llms-full.txt for the Rism docs site.

Reads mkdocs.yml (site_url, site_description, nav order), walks the nav's
markdown pages, and writes two files next to the docs:

  docs/llms.txt       - llmstxt.org index: title, blockquote summary,
                        one link + first-line summary per page
  docs/llms-full.txt  - every page's markdown concatenated under `# <title>`
                        headers with its source URL

Output is deterministic (nav order, no timestamps). Stdlib only; runnable
locally (`python3 scripts/gen-llms.py`) and in pages.yml before
`mkdocs build --strict`. The generated files are NOT committed — CI
regenerates them and mkdocs copies them verbatim into the site root.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MKDOCS_YML = ROOT / "mkdocs.yml"
DOCS = ROOT / "docs"


def config_value(key: str) -> str:
    """Read a top-level scalar key from mkdocs.yml (regex: no YAML dep)."""
    m = re.search(rf"^{key}:\s*(.+?)\s*$", MKDOCS_YML.read_text(encoding="utf-8"), re.M)
    if not m:
        sys.exit(f"gen-llms: {key} not found in mkdocs.yml")
    return m.group(1).strip().strip("'\"")


def nav_pages() -> list[tuple[str, str]]:
    """(title, relative-md-path) in nav order."""
    text = MKDOCS_YML.read_text(encoding="utf-8")
    nav = re.search(r"^nav:\s*\n((?:[ \t]+- .*\n)+)", text, re.M)
    if not nav:
        sys.exit("gen-llms: nav not found in mkdocs.yml")
    pages: list[tuple[str, str]] = []
    for line in nav.group(1).splitlines():
        m = re.match(r"[ \t]+-\s*([^:]+?):\s*(\S+\.md)\s*$", line)
        if m:
            pages.append((m.group(1).strip(), m.group(2).strip()))
    if not pages:
        sys.exit("gen-llms: empty nav")
    return pages


def page_summary(md: str) -> str:
    """First non-heading, non-empty body line, trimmed to one sentence-ish."""
    in_fence = False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence or not line.strip():
            continue
        if line.lstrip().startswith("#"):
            continue
        text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", line)  # links -> label
        text = re.sub(r"[*_`>]", "", text).strip()
        text = re.sub(r"^[-*]\s+", "", text)  # bullet marker is not summary
        return text[:200]
    return ""


def title_of(md: str, fallback: str) -> str:
    m = re.match(r"#\s+(.+)", md)
    return m.group(1).strip() if m else fallback


def main() -> None:
    site_url = config_value("site_url").rstrip("/") + "/"
    site_name = config_value("site_name")
    description = config_value("site_description")

    pages = nav_pages()
    entries = []
    for title, rel in pages:
        path = DOCS / rel
        if not path.is_file():
            sys.exit(f"gen-llms: nav page missing: {rel}")
        md = path.read_text(encoding="utf-8")
        url = site_url + (Path(rel).with_suffix("").as_posix() + "/" if rel != "index.md" else "")
        entries.append((title, rel, url, title_of(md, title), page_summary(md), md))

    index = [f"# {site_name}", "", f"> {description}", ""]
    index += [
        "",
        "Generated by `scripts/gen-llms.py` (deterministic; do not edit by",
        "hand). Full concatenated text: [llms-full.txt](llms-full.txt).",
        "",
        "## Documentation",
        "",
    ]
    index += [
        f"- [{t}]({u}): {s}" for (_, rel, u, t, s, _) in entries if rel != "index.md"
    ]
    (DOCS / "llms.txt").write_text("\n".join(index) + "\n", encoding="utf-8")

    full = [
        f"# {site_name}",
        "",
        f"> {description}",
        "",
        "This file is the concatenation of every documentation page,",
        "in nav order. Generated by `scripts/gen-llms.py`.",
        "",
    ]
    for _, _, url, title, _, md in entries:
        full += ["---", "", f"# {title}", "", f"Source: {url}", "", md.strip(), ""]
    (DOCS / "llms-full.txt").write_text("\n".join(full) + "\n", encoding="utf-8")

    print(f"gen-llms: wrote docs/llms.txt + docs/llms-full.txt ({len(entries)} pages)")


if __name__ == "__main__":
    main()
